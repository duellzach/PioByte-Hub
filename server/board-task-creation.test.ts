/** Development-only authenticated regressions. All writes use a disposable schema. */
import assert from "node:assert/strict";
import crypto from "node:crypto";
import express from "express";
import cookieParser from "cookie-parser";
import { eq } from "drizzle-orm";
import { pool, db } from "./db";
import { users, projects, tasks } from "../shared/schema";
import router from "./routes/tasks";
import { authenticate } from "./middleware/auth";
import { signSession, SESSION_COOKIE } from "./security";
import { taskProjectId } from "./services/taskCreationRules";

if (process.env.NODE_ENV === "production" || process.env.REPLIT_DEPLOYMENT) throw new Error("Board tests must never run against production");
const schema = `board_test_${crypto.randomBytes(6).toString("hex")}`;
const admin = await pool.connect();
let server: ReturnType<express.Express["listen"]> | undefined;
let assertions = 0;
function check(actual: unknown, expected: unknown, label: string) { assert.deepEqual(actual, expected, label); assertions++; }
try {
  await admin.query(`CREATE SCHEMA "${schema}"`);
  for (const table of ["users", "projects", "tasks"]) {
    await admin.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING DEFAULTS)`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)`);
  }
  (pool as any).options.options = `-c search_path=${schema}`;
  await admin.query(`SET search_path TO "${schema}"`);
  await db.insert(users).values([
    {id:1,name:"Fixture coach",username:"fixture_coach",password:"not-a-login",roles:["Coach"]},
    {id:2,name:"Fixture member",username:"fixture_member",password:"not-a-login",roles:["Team Member"],departments:["Mechanical"]},
    {id:3,name:"Fixture leader",username:"fixture_leader",password:"not-a-login",roles:["Department Head"],departments:["Mechanical"]},
  ]);
  await db.insert(projects).values([
    {id:1,name:"Displayed live board",allowAllTaskCreation:true},
    {id:2,name:"Restricted board"},
    {id:3,name:"Archived board",archived:true,allowAllTaskCreation:true},
    {id:4,name:"Own department",department:"Mechanical",allowAllTaskCreation:true},
    {id:5,name:"Other department",department:"Software",allowAllTaskCreation:true},
    {id:6,name:"Permission changed",allowAllTaskCreation:true},
    {id:7,name:"Archive race",allowAllTaskCreation:true},
  ]);
  const app = express(); app.use(express.json()); app.use(cookieParser()); app.use("/api",authenticate,router);
  server = app.listen(0,"127.0.0.1");
  await new Promise<void>(resolve => server!.once("listening",resolve));
  const port=(server.address() as any).port;
  async function create(projectId: unknown, actor=2, claimRoles?:string[], bulk=false) {
    const token=signSession({kind:"member",userId:actor,roles:claimRoles || (actor===1?["Coach"]:actor===3?["Department Head"]:["Team Member"])});
    const result=await fetch(`http://127.0.0.1:${port}/api/tasks${bulk?"/bulk":""}`,{method:"POST",headers:{"Content-Type":"application/json",Cookie:`${SESSION_COOKIE}=${token}`},body:JSON.stringify(bulk?{projectId,tasks:[{title:"Imported fixture"}]}:{projectId,title:"Synthetic new task",departments:["Mechanical"],deptOnly:false})});
    return {status:result.status,body:await result.json()};
  }
  const count=async()=>(await db.select().from(tasks)).length;
  for (const value of [undefined,null,true,"",0,-1,1.5,"1trailing","dept:Mechanical",2147483648]) {
    assert.throws(()=>taskProjectId(value)); assertions++;
  }
  const member=await create(1);
  check(member.status,201,"ordinary member can create on the displayed open board");
  check(member.body.projectId,1,"task persists on the displayed live board, never the archived one");
  check(member.body.status,"Backlog","existing Backlog default is preserved");
  const beforeDenials=await count();
  check((await create(2)).status,403,"restricted board remains leadership-only");
  check((await create(3)).status,409,"member cannot create on archived board");
  check((await create(3,1)).status,409,"coach cannot accidentally create on archived board");
  check((await create(99,1)).status,404,"missing board is reported clearly even to leadership");
  check((await create("1junk")).status,400,"invalid destination is not partially parsed");
  check((await create(5)).status,403,"member cannot create on another department's project");
  check((await create(5,3)).status,403,"department head cannot bypass project visibility");
  check(await count(),beforeDenials,"rejected saves create no hidden tasks");
  check((await create(4)).status,201,"own department open board permits member creation");
  check((await create(5,1)).status,201,"coach retains access to department projects");
  check((await create(2,3)).status,201,"department head retains leadership creation on public board");
  check((await create(2,2,["Coach"])).status,403,"current account permissions override stale leadership claims");
  await db.update(projects).set({allowAllTaskCreation:false}).where(eq(projects.id,6));
  check((await create(6)).status,403,"permission changes while a form is open are enforced at save time");
  check((await create(3,1,undefined,true)).status,409,"bulk import cannot bypass archived-board protection");
  check((await create(1,1,undefined,true)).status,201,"live-board imports still work");
  const beforeRace=await count();
  await admin.query("BEGIN");
  await admin.query("UPDATE projects SET archived = TRUE WHERE id = 7");
  let finished=false;
  const race=create(7).finally(()=>{finished=true;});
  await new Promise(resolve=>setTimeout(resolve,100));
  check(finished,false,"creation waits for an in-progress board archive");
  await admin.query("COMMIT");
  check((await race).status,409,"creation sees the committed archive and does not insert");
  check(await count(),beforeRace,"archive race creates no task");
  console.log(`board creation tests: ${assertions} assertions passed`);
} finally {
  await admin.query("ROLLBACK");
  if (server) await new Promise<void>(resolve=>server!.close(()=>resolve()));
  admin.release();
  await pool.end();
  const pg=await import("pg");
  const cleanup=new pg.default.Pool({connectionString:process.env.DATABASE_URL});
  try { await cleanup.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); } finally {await cleanup.end();}
}
