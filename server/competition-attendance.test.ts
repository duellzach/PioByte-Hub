/**
 * Run: npx tsx server/competition-attendance.test.ts
 * Uses a disposable schema on the DEVELOPMENT database, never production data.
 * Each connection used by the test is scoped to that schema; public data is read
 * only to clone table definitions. Synthetic users have no real credentials.
 */
import assert from "node:assert/strict";
import crypto from "node:crypto";
import express from "express";
import cookieParser from "cookie-parser";
import { pool, db } from "./db";
import { eq } from "drizzle-orm";
import { calendarEvents, scoutEvents, timeEntries, timeEntryAudit, users, teamSettings, eventSignups, timeEntryTaskSegments } from "../shared/schema";
import { startCompetitionSession, changeCompetitionSession } from "./services/competitionSessions";
import { attendanceMinutes } from "./services/competitionSessionRules";
import { firstChanceChanges, credited, validateDecisions } from "./services/firstChanceRules";
import { localDatePT } from "../utils/dates";
import competitionRouter from "./routes/competition";
import timeRouter from "./routes/time";
import eventRouter from "./routes/eventSignups";
import reviewRouter from "./routes/competitionAttendance";
import { authenticate } from "./middleware/auth";
import { signSession, SESSION_COOKIE } from "./security";
import { storage } from "./storage";
import { getTeamTotals } from "./services/hoursLedger";

if (process.env.NODE_ENV === "production") throw new Error("These tests must never run against production");
if (process.env.REPLIT_DEPLOYMENT) throw new Error("These tests are development-only");
const schema = `attendance_test_${crypto.randomBytes(6).toString("hex")}`;
const admin = await pool.connect();
let server: ReturnType<express.Express["listen"]> | undefined;
let assertions = 0;
function check(actual: unknown, expected: unknown, label: string) { assert.deepEqual(actual, expected, label); assertions++; }
const tables = ["users", "calendar_events", "scout_events", "time_entries", "time_entry_audit", "event_signups", "event_signup_shifts", "time_entry_task_segments", "team_settings"];

try {
  await admin.query(`CREATE SCHEMA "${schema}"`);
  for (const table of tables) {
    await admin.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING DEFAULTS)`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 6000)`);
  }
  // admin remains checked out and is used only for schema teardown.
  (pool as any).options.options = `-c search_path=${schema}`;
  await db.insert(users).values([1,7,32,37,42,57,100,101,102,103,104,105,106,107].map(id => ({id, username: `fixture_${id}`, name: `Fixture ${id}`, password: "not-a-login-hash", roles: id === 1 ? ["Coach"] : ["Team Member"]})));
  await db.insert(teamSettings).values({id: 1, timezone: "America/Los_Angeles"});
  const today = localDatePT(new Date(), "America/Los_Angeles");
  await db.insert(scoutEvents).values([
    {id:13,name:"FIRST Chance",startDate:"2026-10-04",endDate:"2026-10-04",createdBy:1},
    {id:700,name:"Synthetic current competition",startDate:today,createdBy:1},
    {id:701,name:"Unlinked current competition",startDate:today,createdBy:1},
  ]);
  await db.insert(calendarEvents).values([
    {id:55,title:"FIRST Chance",startDate:"2026-10-04",type:"competition",createdBy:1},
    {id:700,title:"Synthetic current calendar",startDate:today,type:"competition",scoutEventId:700,createdBy:1},
    {id:701,title:"Unlinked current calendar",startDate:today,type:"competition",createdBy:1},
  ]);
  check(attendanceMinutes("2026-10-04T15:11:00Z", "2026-10-04T15:11:00Z"), 0, "zero duration is not automatically 15 minutes");
  check(attendanceMinutes("2026-10-04T14:58:00.230Z", "2026-10-05T00:35:52.663Z"), 585, "existing quarter-hour policy remains unchanged");
  assert.throws(() => attendanceMinutes(new Date(), new Date(0))); assertions++;
  assert.throws(() => validateDecisions({}, true)); assertions++;

  const app = express(); app.use(express.json()); app.use(cookieParser()); app.use("/api", authenticate);
  app.use("/api", competitionRouter); app.use("/api", timeRouter); app.use("/api", eventRouter); app.use("/api", reviewRouter);
  server = app.listen(0, "127.0.0.1");
  await new Promise<void>(resolve => server!.once("listening", resolve));
  const port = (server.address() as any).port;
  async function request(path: string, method = "GET", body?: unknown, as = 1) {
    const cookie = `${SESSION_COOKIE}=${signSession({kind:"member",userId:as,roles:as===1?["Coach"]:["Team Member"]})}`;
    const result = await fetch(`http://127.0.0.1:${port}/api${path}`, {method, headers: {"Content-Type":"application/json",Cookie:cookie}, ...(body ? {body:JSON.stringify(body)} : {})});
    return {status:result.status,body:result.status===204?null:await result.json()};
  }
  // Scouting-event check-in is retired as a route, but older scouting-event
  // sessions still exist; this seeds one through the shared session service.
  async function legacyScoutCheckIn(userId: number, requestId?: string) {
    return {status:201, body:(await startCompetitionSession({userId,actorId:userId,scoutEventId:700,requestId})).entry as any};
  }

  // Calendar-first and scouting-first: same record and same roster in both orders.
  const calendarFirst = await request("/time-entries/check-in","POST",{userId:100,kind:"competition",calendarEventId:700,requestId:"calendar-first-100"},100);
  const scoutSecond = await legacyScoutCheckIn(100,"scout-second-100");
  check(calendarFirst.status,201,"calendar first succeeds");
  check(scoutSecond.body.id,calendarFirst.body.id,"scouting reuses the calendar session");
  const scoutFirst = await legacyScoutCheckIn(101);
  const calendarSecond = await request("/time-entries/check-in","POST",{userId:101,kind:"competition",calendarEventId:700},101);
  check(calendarSecond.body.id,scoutFirst.body.id,"calendar reuses scouting session");
  const roster = await request("/calendar/700/signups");
  check(roster.body.filter((s:any)=>[100,101].includes(s.userId)).length,2,"both are on the calendar roster");
  const contestList = await request("/competition-checkins?eventId=700");
  check(contestList.body.length,2,"both are in competition attendance");
  const concurrent = await Promise.all(Array.from({length:16},(_,i)=>startCompetitionSession({userId:102,actorId:102,...(i%2?{calendarEventId:700}:{scoutEventId:700})})));
  check(new Set(concurrent.map(r=>r.entry.id)).size,1,"16 concurrent requests create one shared session");
  check(concurrent.filter(r=>r.created).length,1,"exactly one concurrent creation");
  const otherKind = await Promise.allSettled([
    startCompetitionSession({userId:103,actorId:103,scoutEventId:700}),
    storage.createTimeEntry({userId:103,kind:"shop",checkInAt:new Date(),status:"pending_check_in"}),
  ]);
  check(otherKind.filter(r=>r.status==="fulfilled").length,1,"general and competition check-in serialize together");
  const unlinked = await request("/time-entries/check-in","POST",{userId:107,kind:"competition",calendarEventId:701},107);
  check(unlinked.status,201,"an unlinked calendar competition accepts check-in");
  check(unlinked.body.scoutEventId,null,"unlinked calendar session carries no scouting identity");
  check((await request("/calendar/701/signups")).body.some((s:any)=>s.userId===107),true,"unlinked calendar check-in appears on its roster");
  check((await request("/competition-checkins/check-in","POST",{userId:104,eventId:700},104)).status,410,"scouting-event check-in is retired");
  await assert.rejects(startCompetitionSession({userId:104,actorId:104,scoutEventId:701}),(e:any)=>e.status===409); assertions++;
  check((await request("/time-entries/check-in","POST",{userId:105,kind:"competition",calendarEventId:700},104)).status,403,"cannot check someone else in");
  check((await request(`/competition-checkins/${calendarFirst.body.id}/check-out`,"POST",{},104)).status,403,"cannot check someone else out");
  const checkout = await request(`/competition-checkins/${calendarFirst.body.id}/check-out`,"POST",{},100);
  check(checkout.body.status,"pending_approval","competition checkout shares pending approval state");
  const approve = await request(`/time-entries/${calendarFirst.body.id}/confirm`,"POST",{confirmType:"check_out",coachId:999});
  check(approve.body.status,"completed","general approval resolves competition checkout");
  check(approve.body.checkOutConfirmedBy,1,"approval uses authenticated coach, not supplied actor");
  check((await request(`/competition-checkins/${calendarFirst.body.id}/approve`,"POST",{})).body.roundedMinutes,0,"repeat approval cannot add minimum credit");
  check((await request(`/competition-checkins/${calendarFirst.body.id}/approve`,"POST",{roundedMinutes:15})).status,409,"second approval cannot overwrite resolved minutes");
  const retryAfterClose = await request("/time-entries/check-in","POST",{userId:100,kind:"competition",calendarEventId:700,requestId:"calendar-first-100"},100);
  check(retryAfterClose.body.id,calendarFirst.body.id,"delayed retry returns original even after checkout");
  const nextVisit = await startCompetitionSession({userId:100,actorId:100,scoutEventId:700,requestId:"legitimate-next-visit"});
  assert.notEqual(nextVisit.entry.id,calendarFirst.body.id); assertions++;
  const earlier = (await storage.getTimeEntry(calendarFirst.body.id))!;
  const oldEdit = await request(`/time-entries/${earlier.id}`,"PUT",{checkInAt:new Date(earlier.checkInAt.getTime()-60_000).toISOString(),reason:"Verified earlier arrival on first visit"});
  check(oldEdit.status,200,"an earlier approved visit can be edited while a later visit is open");
  const stillPresent = (await request("/calendar/700/signups")).body.find((s:any)=>s.userId===100);
  check(new Date(stillPresent.checkedInAt).getTime(),nextVisit.entry.checkInAt.getTime(),"editing the first visit preserves the later roster check-in");
  check(stillPresent.checkedOutAt,null,"editing the first visit does not mark the currently present member absent");
  const pendingEarlier = await legacyScoutCheckIn(105);
  await request(`/competition-checkins/${pendingEarlier.body.id}/check-out`,"POST",{},105);
  const laterOpen = await request("/time-entries/check-in","POST",{userId:105,kind:"competition",calendarEventId:700},105);
  check((await request(`/competition-checkins/${pendingEarlier.body.id}/reject`,"POST",{})).body.status,"rejected","earlier pending visit is rejected with a later visit open");
  const stillPresentAfterReject = (await request("/calendar/700/signups")).body.find((s:any)=>s.userId===105);
  check(new Date(stillPresentAfterReject.checkedInAt).getTime(),new Date(laterOpen.body.checkInAt).getTime(),"rejecting the first visit preserves the later roster check-in");
  check(stillPresentAfterReject.checkedOutAt,null,"rejecting the first visit does not clear present-member attendance");
  const approvalEarlier = await request("/time-entries/check-in","POST",{userId:106,kind:"competition",calendarEventId:700},106);
  await request(`/time-entries/${approvalEarlier.body.id}/check-out`,"POST",{},106);
  const approvalLater = await legacyScoutCheckIn(106);
  check((await request(`/competition-checkins/${approvalEarlier.body.id}/approve`,"POST",{})).status,200,"earlier pending visit may be approved after the next visit starts");
  const stillPresentAfterApproval = (await request("/calendar/700/signups")).body.find((s:any)=>s.userId===106);
  check(stillPresentAfterApproval.checkedOutAt,null,"earlier approval does not close the later roster attendance");
  check(new Date(stillPresentAfterApproval.checkedInAt).getTime(),new Date(approvalLater.body.checkInAt).getTime(),"earlier approval preserves the current check-in identity");
  const [signup101] = await db.select().from(eventSignups).where(eq(eventSignups.userId,101));
  const rosterCheckout = await request("/calendar/700/checkout","POST",{signupId:signup101.id});
  check(rosterCheckout.status,200,"calendar roster can close and approve the shared record");
  check((await request(`/competition-checkins?eventId=700`)).body.find((e:any)=>e.id===scoutFirst.body.id).status,"approved","scouting sees roster approval");
  const rejected = concurrent[0].entry;
  check((await request(`/competition-checkins/${rejected.id}/reject`,"POST",{})).body.status,"rejected","pending session can be rejected");
  check((await request(`/time-entries/${rejected.id}/confirm`,"POST",{confirmType:"check_out"})).status,409,"general confirmation cannot revive rejected session");
  await request("/time-entries"); // Old GET normalizer used to revive rejected entries.
  check((await storage.getTimeEntry(rejected.id))!.status,"rejected","reading time entries never revives rejection");
  const [rejectedSignup] = await db.select().from(eventSignups).where(eq(eventSignups.userId,102));
  check(rejectedSignup.checkedInAt,null,"rejected session no longer appears present on roster");
  const override = await startCompetitionSession({userId:104,actorId:104,scoutEventId:700});
  await changeCompetitionSession(override.entry.id,104,"checkout");
  check((await request(`/competition-checkins/${override.entry.id}/approve`,"POST",{roundedMinutes:15})).status,400,"manual credit requires a reason");
  check((await request(`/competition-checkins/${override.entry.id}/approve`,"POST",{roundedMinutes:15,reason:"Verified exceptional credit"})).status,200,"explained adjustment is auditable");
  check((await request("/competition-checkins/manual-add","POST",{userId:105,eventId:700,minutes:15,notes:"Coach verified exceptional credit"})).status,410,"scouting-event manual add is retired");
  check((await request("/competition-attendance/links","PUT",{calendarEventId:701,scoutEventId:700})).status,409,"one scouting identity cannot be linked to two calendars");
  const testSession = await storage.getTimeEntry(scoutFirst.body.id);
  check((await request(`/time-entries/${testSession!.id}`,"PUT",{checkOutAt:"invalid date",notes:"Coach verified departure change"})).status,400,"invalid attendance dates fail explicitly");
  const beforeOverrideAudits=(await storage.getTimeEntryAudit(override.entry.id)).length;
  await request(`/time-entries/${override.entry.id}/confirm`,"POST",{confirmType:"check_in"});
  check((await storage.getTimeEntry(override.entry.id))!.status,"completed","check-in confirmation cannot reopen a completed session");
  check((await storage.getTimeEntryAudit(override.entry.id)).length,beforeOverrideAudits,"resolved confirmation retry is audit-idempotent");
  await request(`/time-entries/${override.entry.id}`,"PUT",{notes:"New note without changing manual credit"});
  check((await storage.getTimeEntry(override.entry.id))!.roundedMinutes,15,"notes-only edits preserve exceptional manual minutes");

  // Historical cases are synthetic and contain only the investigated time intervals.
  const fixtures = [
    [2487,37,55,null,"2026-10-04T14:58:00.230Z","2026-10-04T15:15:18.889Z",30],
    [2489,32,55,null,"2026-10-04T14:59:37.982Z","2026-10-05T00:19:57.348Z",570],
    [2492,32,null,13,"2026-10-04T15:00:03.191Z","2026-10-05T00:19:46.675Z",570],
    [2493,42,55,null,"2026-10-04T15:00:18.449Z","2026-10-05T00:50:47.158Z",600],
    [2494,42,null,13,"2026-10-04T15:00:21.292Z","2026-10-05T00:21:52.264Z",570],
    [2495,7,55,null,"2026-10-04T15:09:40.640Z","2026-10-05T00:50:43.597Z",585],
    [2496,7,null,13,"2026-10-04T15:09:44.365Z","2026-10-05T00:49:33.477Z",585],
    [2499,57,null,13,"2026-10-04T15:11:00.000Z","2026-10-04T15:11:00.000Z",15],
    [2503,37,null,13,"2026-10-04T15:15:15.805Z","2026-10-05T00:35:52.663Z",570],
    [2504,57,null,13,"2026-10-04T15:15:55.254Z","2026-10-05T02:20:26.585Z",675],
  ].map(([id,userId,calendarEventId,scoutEventId,checkInAt,checkOutAt,roundedMinutes])=>({id:Number(id),userId:Number(userId),calendarEventId:calendarEventId as number|null,scoutEventId:scoutEventId as number|null,checkInAt:new Date(checkInAt as string),checkOutAt:new Date(checkOutAt as string),roundedMinutes:Number(roundedMinutes),kind:"competition",status:"completed",checkOutConfirmedBy:1}));
  await db.insert(timeEntries).values(fixtures);
  await db.insert(timeEntryTaskSegments).values({entryId:2496,userId:7,startedAt:fixtures[6].checkInAt,endedAt:fixtures[6].checkOutAt,minutes:580});
  for (const departure of ["calendar","scout"] as const) for (const switchChoice of ["preserve","merge"] as const) for (const zero of ["keep","remove"] as const) {
    const decisions={departure,switch:switchChoice,zero};
    const changes=firstChanceChanges(fixtures,decisions);
    const after=fixtures.reduce((sum,e)=>sum+credited({...e,...changes.find(c=>c.id===e.id)}),0);
    const expected=fixtures.reduce((sum,e)=>sum+credited(e),0)-1725-(departure==="scout"?30:0)-(switchChoice==="merge"?15:0)-(zero==="remove"?15:0);
    check(after,expected,`review totals for ${JSON.stringify(decisions)}`);
    assert(!changes.some(c=>c.id===2504)); assertions++;
  }
  check((await request("/competition-attendance/first-chance/preview","GET",undefined,100)).status,403,"historical review is coach-only");
  check((await request("/competition-attendance/links","PUT",{calendarEventId:55,scoutEventId:13})).status,200,"coach explicitly links FIRST Chance IDs");
  const decisions={departure:"scout",switch:"merge",zero:"remove"};
  const preview=await request("/competition-attendance/first-chance/preview","POST",{decisions});
  check(preview.body.cases.length,5,"all three duplicates and two review-only cases visible");
  check(preview.body.beforeMinutes-preview.body.afterMinutes,1785,"preview reflects all approved review choices");
  check((await getTeamTotals("2026-10-04","2026-10-04")).competition,preview.body.beforeMinutes,"correction preview agrees with the original hours ledger");
  check((await request("/competition-attendance/first-chance/apply","POST",{fingerprint:preview.body.fingerprint,reason:"Verified attendance evidence",confirmed:true,linkConfirmed:true,decisions:{}})).status,400,"unresolved choices cannot be applied");
  await db.insert(timeEntryAudit).values({entryId:2489,actorId:1,actionType:"fixture_review_note",newValues:{notes:"new evidence"}});
  const applyBody={fingerprint:preview.body.fingerprint,reason:"Verified attendance evidence and coach review",confirmed:true,linkConfirmed:true,decisions};
  check((await request("/competition-attendance/first-chance/apply","POST",applyBody)).status,409,"changed evidence prevents stale apply");
  const fresh=await request("/competition-attendance/first-chance/preview","POST",{decisions});
  applyBody.fingerprint=fresh.body.fingerprint;
  const unrelatedBefore=await storage.getTimeEntry(scoutFirst.body.id);
  const applied=await request("/competition-attendance/first-chance/apply","POST",applyBody);
  check(applied.status,200,"authenticated coach can apply reviewed correction");
  check(applied.body.applied,true,"review is recorded as applied");
  check(applied.body.beforeMinutes,fresh.body.beforeMinutes,"applied review preserves original before totals");
  check(applied.body.afterMinutes,fresh.body.afterMinutes,"applied review confirms the proposed after totals");
  check((await getTeamTotals("2026-10-04","2026-10-04")).competition,applied.body.afterMinutes,"corrected hours ledger agrees with the approved preview");
  check((await storage.getTimeEntry(2496))!.status,"rejected","redundant credit is rejected, not deleted");
  check((await storage.getTimeEntry(2504))!.roundedMinutes,675,"legitimate later visit remains unchanged");
  check((await db.select().from(timeEntryTaskSegments).where(eq(timeEntryTaskSegments.entryId,2496))).length,1,"original task attribution survives correction");
  check(await storage.getTimeEntry(scoutFirst.body.id),unrelatedBefore,"unrelated entries remain byte-for-byte unchanged");
  const auditCount=(await db.select().from(timeEntryAudit)).length;
  check((await request("/competition-attendance/first-chance/apply","POST",applyBody)).status,200,"repeat application is a no-op");
  check((await db.select().from(timeEntryAudit)).length,auditCount,"repeat application creates no duplicate audit records");
  await request("/time-entries");
  check((await storage.getTimeEntry(2496))!.status,"rejected","reading all entries after repair cannot revive duplicates");
  check((await request("/competition-checkins/2496/approve","POST",{})).status,409,"dedicated approval cannot revive repaired duplicates");
  check((await request("/competition-checkins/2496","DELETE")).status,409,"reviewed duplicate history cannot be deleted");
  const [signup7]=await db.select().from(eventSignups).where(eq(eventSignups.userId,7));
  check((await request(`/signups/${signup7.id}/attendance`,"PATCH",{checkedOutAt:"2026-10-05T00:50:43.597Z",reason:"Reviewed unchanged departure time"})).status,200,"roster edits address the surviving visit");
  check((await storage.getTimeEntry(2496))!.status,"rejected","roster edits cannot revive rejected duplicate");
  check((await request("/calendar/55/signups")).body.find((s:any)=>s.userId===7).clockedMinutes,585,"roster totals count only surviving credit");
  const audited = await storage.getTimeEntryAudit(2493);
  check(audited.find(a=>a.actionType==="first_chance_correction")!.newValues!.reason,applyBody.reason,"correction records authenticated coach's explanation");
  check((await request("/competition-attendance/first-chance/preview")).body.cases.find((c:any)=>c.key==="departure").entries[0].roundedMinutes,600,"original conflicting credit remains visible after correction");
  console.log(`competition attendance tests: ${assertions} assertions passed`);
} finally {
  if (server) await new Promise<void>(resolve => server!.close(()=>resolve()));
  // Dispose every test connection before dropping the schema.
  admin.release();
  await pool.end();
  const pg = await import("pg");
  const cleanup = new pg.default.Pool({connectionString:process.env.DATABASE_URL});
  try { await cleanup.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); } finally { await cleanup.end(); }
}
