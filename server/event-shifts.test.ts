/**
 * Run: npx tsx server/event-shifts.test.ts
 * Multi-shift event sign-ups: one person, several shifts, per-shift capacity,
 * waitlist and approval. Uses a disposable schema on the DEVELOPMENT database
 * (same harness as competition-attendance.test.ts); synthetic users only.
 */
import assert from "node:assert/strict";
import crypto from "node:crypto";
import express from "express";
import cookieParser from "cookie-parser";
import { pool, db } from "./db";
import { calendarEvents, eventShifts, eventSignups, users, teamSettings } from "../shared/schema";
import eventRouter from "./routes/eventSignups";
import calendarRouter from "./routes/calendar";
import { authenticate } from "./middleware/auth";
import { signSession, SESSION_COOKIE } from "./security";
import { storage } from "./storage";

if (process.env.NODE_ENV === "production") throw new Error("These tests must never run against production");
if (process.env.REPLIT_DEPLOYMENT) throw new Error("These tests are development-only");
const schema = `shifts_test_${crypto.randomBytes(6).toString("hex")}`;
const admin = await pool.connect();
let server: ReturnType<express.Express["listen"]> | undefined;
let assertions = 0;
function check(actual: unknown, expected: unknown, label: string) { assert.deepEqual(actual, expected, label); assertions++; }
const tables = ["users", "calendar_events", "event_shifts", "event_signups", "time_entries", "team_settings"];

try {
  await admin.query(`CREATE SCHEMA "${schema}"`);
  for (const table of tables) {
    await admin.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING DEFAULTS)`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id DROP DEFAULT`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 6000)`);
    await admin.query(`ALTER TABLE "${schema}"."${table}" ADD PRIMARY KEY (id)`);
  }
  // LIKE doesn't copy indexes; event_signup_shifts' foreign keys need the
  // primary keys above and the sign-up upserts rely on this one.
  await admin.query(`CREATE UNIQUE INDEX ON "${schema}".event_signups (calendar_event_id, user_id)`);
  (pool as any).options.options = `-c search_path=${schema}`;
  await storage.ensureSchemaMigrationsTable();
  await storage.ensureSignupShiftsTable();

  // 1 = Coach (cap-exempt), 10..13 = students.
  await db.insert(users).values([1, 10, 11, 12, 13].map(id => ({ id, username: `fixture_${id}`, name: `Fixture ${id}`, password: "not-a-login-hash", roles: id === 1 ? ["Coach"] : ["Team Member"] })));
  await db.insert(teamSettings).values({ id: 1, timezone: "America/Los_Angeles", roles: [{ name: "Coach", excludeFromCaps: true }, { name: "Team Member" }] } as any);
  await db.insert(calendarEvents).values({ id: 500, title: "Outreach day", startDate: "2099-01-01", type: "outreach", signupEnabled: true, createdBy: 1 } as any);
  await db.insert(eventShifts).values([
    { id: 1, calendarEventId: 500, title: "Morning", startTime: "08:00", endTime: "12:00", capacity: 1 },
    { id: 2, calendarEventId: 500, title: "Afternoon", startTime: "12:00", endTime: "16:00", capacity: null },
    { id: 3, calendarEventId: 500, title: "Evening", startTime: "16:00", endTime: "20:00", capacity: 5 },
  ]);

  const app = express(); app.use(express.json()); app.use(cookieParser()); app.use("/api", authenticate); app.use("/api", eventRouter); app.use("/api", calendarRouter);
  server = app.listen(0, "127.0.0.1");
  await new Promise<void>(resolve => server!.once("listening", resolve));
  const port = (server.address() as any).port;
  async function request(path: string, method = "GET", body?: unknown, as = 1) {
    const cookie = `${SESSION_COOKIE}=${signSession({ kind: "member", userId: as, roles: as === 1 ? ["Coach"] : ["Team Member"] })}`;
    const result = await fetch(`http://127.0.0.1:${port}/api${path}`, { method, headers: { "Content-Type": "application/json", Cookie: cookie }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: result.status, body: result.status === 204 ? null : await result.json() };
  }
  const myRow = async (userId: number) => (await request("/calendar/500/signups")).body.find((s: any) => s.userId === userId);
  const shiftStatus = (row: any, shiftId: number) => row.shifts.find((s: any) => s.shiftId === shiftId)?.status;

  check((await request("/calendar/500/signup", "POST", {}, 10)).status, 400, "a shift event requires at least one shift");
  check((await request("/calendar/500/signup", "POST", { shiftIds: [99] }, 10)).status, 400, "unknown shifts are rejected");

  // One person, two shifts at once.
  const two = await request("/calendar/500/signup", "POST", { shiftIds: [1, 2] }, 10);
  check(two.status, 201, "signing up for two shifts succeeds");
  check(two.body.shifts.map((s: any) => s.shiftId).sort(), [1, 2], "both shifts are held");
  check((await db.select().from(eventSignups)).filter(s => s.userId === 10).length, 1, "still one event sign-up per person");

  // Adding a third later keeps the first two.
  await request("/calendar/500/signup", "POST", { shiftIds: [3] }, 10);
  check((await myRow(10)).shifts.length, 3, "a later sign-up adds shifts without dropping earlier ones");

  // Per-shift approval derives the event-level status.
  const row10 = await myRow(10);
  check(row10.status, "requested", "nothing approved yet");
  const morning10 = row10.shifts.find((s: any) => s.shiftId === 1);
  check((await request(`/signup-shifts/${morning10.id}`, "PUT", { status: "accepted" })).status, 200, "coach accepts one shift");
  const after = await myRow(10);
  check(shiftStatus(after, 1), "accepted", "only that shift is accepted");
  check(shiftStatus(after, 2), "requested", "other shifts keep their own status");
  check(after.status, "accepted", "event-level status is accepted once any shift is");
  check((await request(`/signup-shifts/${morning10.id}`, "PUT", { status: "accepted" }, 11)).status, 403, "students cannot approve shifts");

  // Capacity is per shift: Morning (cap 1) is full, Afternoon is unlimited.
  const full = await request("/calendar/500/signup", "POST", { shiftIds: [1, 2] }, 11);
  check(shiftStatus(full.body, 1), "waitlisted", "a full shift waitlists");
  check(shiftStatus(full.body, 2), "requested", "the same request still gets an open shift");
  const coach = await request("/calendar/500/signup", "POST", { shiftIds: [1] }, 1);
  check(shiftStatus(coach.body, 1), "accepted", "cap-exempt sign-ups are accepted even on a full shift");
  check((await request("/calendar/500/shifts")).body.find((s: any) => s.id === 1).acceptedCount, 1, "cap-exempt sign-ups don't count toward the shift cap");

  // Withdrawing one shift keeps the rest; withdrawing the last leaves the event.
  check((await request("/calendar/500/signup?shiftId=2", "DELETE", undefined, 11)).status, 204, "withdraw one shift");
  const left = await myRow(11);
  check(left.shifts.map((s: any) => s.shiftId), [1], "the other shift remains");
  check(left.status, "waitlisted", "event-level status follows the remaining shift");
  await request("/calendar/500/signup?shiftId=1", "DELETE", undefined, 11);
  check(await myRow(11), undefined, "dropping the last shift withdraws from the event");

  // Coach adds / removes someone from a shift.
  await request("/calendar/500/signup", "POST", { shiftIds: [2] }, 12);
  const row12 = await myRow(12);
  check((await request(`/signups/${row12.id}/shifts`, "POST", { shiftId: 3 })).status, 201, "coach adds a person to another shift");
  const added = await myRow(12);
  check(shiftStatus(added, 3), "accepted", "coach-added shifts are accepted");
  check((await request(`/signups/${row12.id}/shifts`, "POST", { shiftId: 99 })).status, 400, "coach can't add a shift from another event");
  await request(`/signup-shifts/${added.shifts.find((s: any) => s.shiftId === 3).id}`, "DELETE");
  const removed = await myRow(12);
  check(removed.shifts.map((s: any) => s.shiftId), [2], "coach removes a person from one shift");
  check(removed.status, "requested", "event-level status re-derives after removal");

  // Upcoming card reports each held shift.
  const upcoming = (await request("/me/upcoming", "GET", undefined, 10)).body.find((e: any) => e.id === 500);
  check(upcoming.myShifts.length, 3, "upcoming lists every shift the person holds");

  // Legacy single-shift sign-ups (event_signups.shift_id) are backfilled once.
  const [legacy] = await db.insert(eventSignups).values({ calendarEventId: 500, userId: 13, status: "accepted", shiftId: 2 } as any).returning();
  await storage.backfillSignupShifts();
  await storage.backfillSignupShifts();
  check((await storage.getSignupShifts(legacy.id)).map(s => [s.shiftId, s.status]), [[2, "accepted"]], "legacy shift_id becomes one shift row, exactly once");

  console.log(`event shift tests: ${assertions} assertions passed`);
} finally {
  if (server) await new Promise<void>(resolve => server!.close(() => resolve()));
  admin.release();
  await pool.end();
  const pg = await import("pg");
  const cleanup = new pg.default.Pool({ connectionString: process.env.DATABASE_URL });
  try { await cleanup.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); } finally { await cleanup.end(); }
}
